/*
& 2. Michelin Stars
~ Many restaurants dream of earning a Michelin Star. While achieving the maximum three stars is extraordinary, even one star can be life-changing. 🍽️
~ Create a system to award Michelin stars
~ Define a rating variable as a number between 1 and 3, and log one of the following based on the number:
    ~ '🌟 is worth walking to.'
    ~ '🌟🌟 is worth driving to.'
    ~ '🌟🌟🌟 is worth flying to.'
    ~ All other cases, log 'Invalid'
*/

let rating = 1;

if (rating === 1) {
    console.log('🌟 is worth walking to');
} else if (rating === 2) {
    console.log('🌟🌟 is worth driving to');
} else if (rating === 3) {
    console.log('🌟🌟🌟 is worth flying to');
} else {
    console.log('Invalid');
}
console.log();

